def test_explorer_toml_round_trips():
    """The explorer's own output, downloaded from the page and kept verbatim.

    `workingsetConfig` in interactive/src/harness.js writes these field names
    from the live controls; this is the assertion that the two sides still
    agree. DP2 at 200 users with a 512 GiB offload buffer, so the per-group
    conversions are exercised: users 200/2, ram_gib 512/2.
    """
    p = Path(__file__).resolve().parent / "fixtures" / "explorer_workingset.toml"
    cfg = load_config(p)
    d, w, slo, ep, cal = (cfg.deployment, cfg.workload, cfg.slo,
                          cfg.endpoint, cfg.calibration)
    assert (d.model, d.gpu) == ("35BA3B", "H200")
    assert (d.tensor_parallel, d.replicas) == (1, 2)
    assert (d.weight_dtype, d.kv_dtype) == ("fp8", "fp8")
    assert d.max_num_batched_tokens == 32_768 and d.max_model_len == 180_000
    assert d.ram_gib == 256                        # 512 GiB shared / 2 groups
    assert d.gpus == "2xH200"
    assert w.users == 100                          # 200 users / 2 groups
    assert (w.system_prefix_tokens, w.user_prompt_median_tokens) == (15_000, 31_000)
    assert (w.user_prompt_sigma, w.subagent_sigma) == (0.81, 0.9)
    assert (w.warm_turn_tokens, w.max_output_tokens) == (2_000, 400)
    assert (w.think_time_s, w.miss_rate, w.subagent_ratio) == (30, 0.01, 0.1)
    assert (w.subagent_median_tokens, w.subagent_prefix_tokens) == (8_000, 3_000)
    assert w.sub_shares_prefix is False
    assert (slo.ttft_budget_s, slo.itl_floor_tok_s, slo.percentile) == (10, 40, 95)
    assert ep.base_url == "http://localhost:8000/v1" and ep.api_key_env == "VLLM_API_KEY"
    assert (cal.mfu, cal.mbu) == (M.MFU_DEFAULT, M.MBU_DEFAULT)
    cfg.validate()
    # no predictions travel in the file, and re-dumping it changes nothing
    assert load_config(p) == RunConfig.from_dict(tomllib.loads(cfg.dumps("toml")))


def test_explorer_toml_names_every_field():
    """A field added to RunConfig and not to the explorer's writer would give
    users a config whose defaults silently differ from what they set."""
    p = Path(__file__).resolve().parent / "fixtures" / "explorer_workingset.toml"
    raw = tomllib.loads(p.read_text(encoding="utf-8"))
    for block, typ in (("deployment", Deployment), ("workload", WorkloadCfg),
                       ("slo", SLO), ("endpoint", Endpoint),
                       ("calibration", Calibration)):
        want = {f.name for f in dataclass_fields(typ)}
        want -= {"metrics_url"}          # optional: no /metrics on the page
        assert want == set(raw[block]), f"{block}: {want ^ set(raw[block])}"


