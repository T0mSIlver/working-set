import json
import math

import pytest

from workingset import model as M
from workingset.config import RunConfig, load_config
from workingset.predict import predict


def test_defaults_round_trip_toml(tmp_path):
    cfg = RunConfig()
    p = tmp_path / "workingset.toml"
    p.write_text(cfg.dumps("toml"))
    assert load_config(p) == cfg


def test_defaults_round_trip_json(tmp_path):
    cfg = RunConfig()
    p = tmp_path / "workingset.json"
    p.write_text(cfg.dumps("json"))
    assert load_config(p) == cfg


def test_unknown_key_rejected():
    with pytest.raises(ValueError, match="unknown key workload.foo"):
        RunConfig.from_dict({"workload": {"foo": 1}})
    with pytest.raises(ValueError, match="unknown top-level"):
        RunConfig.from_dict({"nope": {}})


def test_schema_version_gate():
    with pytest.raises(ValueError, match="schema_version"):
        RunConfig.from_dict({"schema_version": 99})


def test_default_workload_matches_model_defaults():
    """The config's defaults ARE the study's measured defaults, field by field."""
    wl = RunConfig().to_workload()
    ref = M.Workload()
    for f in ("user_median", "user_sigma", "sub_median", "sub_sigma", "sub_ratio",
              "sys_user", "sys_sub", "sub_shares_prefix", "invalidation", "cap"):
        assert getattr(wl, f) == getattr(ref, f), f


