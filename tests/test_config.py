def test_legacy_harness_config_block(tmp_path):
    """An explorer-generated harness download still loads."""
    block = {
        "endpoint": {"base_url": "http://x/v1", "model": "m", "api_key_env": "K"},
        "deployment": {"gpus": "4xH200", "tensor_parallel": 4, "replicas": 1,
                       "max_num_batched_tokens": 4096, "max_model_len": 180000},
        "workload": {"system_prefix_tokens": 15000, "user_prompt_median_tokens": 31000,
                     "user_prompt_sigma": 0.81, "warm_turn_tokens": 2000,
                     "think_time_s": 30.0, "subagent_ratio": 0.1,
                     "subagent_median_tokens": 8000, "subagent_sigma": 0.9,
                     "miss_rate": 0.01, "max_output_tokens": 400,
                     "context_cap_tokens": 180000, "subagent_prefix_tokens": 3000,
                     "sub_shares_prefix": False},
        "slo": {"ttft_budget_s": 10.0, "itl_floor_tok_s": 40, "percentile": 95},
        "predictions": {"warm_capacity_p5": 403},
        "hypotheses": ["H-cache: ..."],
    }
    src = ('# --- BEGIN CONFIG (generated by the interactive explorer) ---\n'
           'CONFIG = json.loads(r"""\n' + json.dumps(block, indent=4) +
           '\n""")\n# --- END CONFIG ---\n')
    p = tmp_path / "downloaded_harness.py"
    p.write_text(src)
    cfg = load_config(p)
    assert cfg.deployment.gpu == "H200"
    assert cfg.deployment.tensor_parallel == 4
    assert cfg.deployment.max_num_batched_tokens == 4096
    assert cfg.deployment.max_model_len == 180000
    assert cfg.workload.miss_rate == 0.01
    assert cfg.endpoint.base_url == "http://x/v1"
    # the harness names only the served checkpoint: no model key is guessed
    assert cfg.deployment.model is None
    with pytest.raises(ValueError, match="pass --model"):
        cfg.validate()
    with pytest.raises(ValueError, match="model"):
        cfg.dumps("toml")
    # the load the predictions were computed at is the operating point
    block["predictions"]["operating_point_users"] = 400
    p.write_text('CONFIG = json.loads(r"""\n' + json.dumps(block, indent=4) + '\n""")\n')
    assert load_config(p).workload.users == 400


