"""Write the explorer's copy of the API and coding-plan prices.

src/workingset/data/api_prices.toml is the source; interactive/src/
api_prices.js is generated from it so the explorer prices the numbers
workingset.api_cost loads. Run after editing the TOML:

    uv run scripts/api_prices.py           # rewrite interactive/src/api_prices.js
    uv run scripts/api_prices.py --check   # exit 1 if it is stale (CI, tests)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from workingset.api_cost import load_prices

OUT = Path(__file__).resolve().parents[1] / "interactive" / "src" / "api_prices.js"
HEADER = ("// GENERATED by scripts/api_prices.py from src/workingset/data/api_prices.toml.\n"
          "// Do not edit: change the TOML and rerun the script.\n")


def render() -> str:
    body = json.dumps(load_prices(), indent=1, ensure_ascii=False)
    return f"{HEADER}export const API_PRICES = {body};\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale: run `uv run scripts/api_prices.py`", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
