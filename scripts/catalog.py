"""Write the explorer's copy of the model and GPU catalogue.

src/workingset/data/catalog.toml is the source; interactive/src/catalog.js
is generated from it so the explorer prices the numbers workingset.model
loads. Run after editing the TOML:

    uv run scripts/catalog.py           # rewrite interactive/src/catalog.js
    uv run scripts/catalog.py --check   # exit 1 if it is stale (CI, tests)
"""
from __future__ import annotations

import dataclasses
import json
import sys
from pathlib import Path

from workingset.model import GPU, Model, load_catalog

OUT = Path(__file__).resolve().parents[1] / "interactive" / "src" / "catalog.js"
HEADER = ("// GENERATED by scripts/catalog.py from src/workingset/data/catalog.toml.\n"
          "// Do not edit: change the TOML and rerun the script.\n")


def _defaults(cls) -> dict:
    """The dataclass defaults the TOML leaves out. None defaults stay out:
    the explorer reads an absent field as None."""
    return {f.name: f.default for f in dataclasses.fields(cls)
            if f.default is not dataclasses.MISSING and f.default is not None}


def render() -> str:
    cat = load_catalog()
    cat["defaults"] = {"gpu": _defaults(GPU), "model": _defaults(Model)}
    body = json.dumps(cat, indent=1, ensure_ascii=False)
    return f"{HEADER}export const CATALOG = {body};\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale: run `uv run scripts/catalog.py`", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
