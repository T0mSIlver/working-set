"""Write the explorer's copy of the model and GPU catalogue.

src/workingset/data/catalog.toml is the source; interactive/src/catalog.js
is generated from it so the explorer prices the numbers workingset.model
loads. Run after editing the TOML:

    uv run scripts/catalog.py           # rewrite interactive/src/catalog.js
    uv run scripts/catalog.py --check   # exit 1 if it is stale (CI, tests)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from workingset.model import load_catalog

OUT = Path(__file__).resolve().parents[1] / "interactive" / "src" / "catalog.js"
HEADER = ("// GENERATED by scripts/catalog.py from src/workingset/data/catalog.toml.\n"
          "// Do not edit: change the TOML and rerun the script.\n")


def render() -> str:
    body = json.dumps(load_catalog(), indent=1, ensure_ascii=False)
    return f"{HEADER}export const CATALOG = {body};\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale: run `uv run scripts/catalog.py`", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
