"""Rewrite the "Provider fidelity" table in docs/market.md from
data/market/provider_prices.json, the publishable price source.

    uv run scripts/market_fidelity_doc.py           # rewrite the table
    uv run scripts/market_fidelity_doc.py --check   # exit 1 if it is stale
"""
from __future__ import annotations

import sys
from pathlib import Path

from workingset import market as MK
from workingset import model as M

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "market.md"
BEGIN = "<!-- BEGIN fidelity table: generated by scripts/market_fidelity_doc.py -->"
END = "<!-- END fidelity table -->"


def table() -> str:
    snap = MK.load_snapshot(ROOT / "data" / "market")
    pp = [s for s in snap["prices"] if s["file"] == "provider_prices.json"]
    if not pp:
        raise SystemExit("data/market/provider_prices.json not found")
    snap = {**snap, "prices": pp}
    wv = MK.default_workload()
    rows = [MK.fidelity_summary(k, MK.provider_rows(snap, k, wv, MK.CACHE_TTL_DEFAULT))
            for k in M.MODELS]
    return MK.fidelity_table([r for r in rows if r["rows"]])


def main(argv: list[str]) -> int:
    text = DOC.read_text()
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{DOC}: the {BEGIN!r} / {END!r} markers are missing")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = f"{head}{BEGIN}\n{table()}\n{END}{tail}"
    if "--check" in argv:
        if new != text:
            print(f"{DOC.relative_to(ROOT)} is stale: run uv run scripts/market_fidelity_doc.py",
                  file=sys.stderr)
            return 1
        return 0
    DOC.write_text(new)
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
