async def main_async(args, cfg, state: dict):
    import httpx  # lazy: --dry-run must work without any dependency installed

    limits = httpx.Limits(max_connections=4096, max_keepalive_connections=256)
    async with httpx.AsyncClient(limits=limits) as client:
        if args.burst:
            await run_burst(client, args, cfg, state)
            return
        ladder = build_ladder(args, cfg)
        print(f"ladder: {ladder} users "
              f"(ramp {args.ramp_s:g}s + measure {args.measure_s:g}s each)")
        for pop in ladder:
            print(f"\n--- rung: {pop} users ---")
            res = await run_rung(client, args, cfg, pop, state)
            verdict = "PASS" if res.passed else "FAIL (" + "; ".join(res.reasons) + ")"
            print(f"  TTFT hit p50 {fmt(res.ttft_hit_p50, 's')} / miss p50 "
                  f"{fmt(res.ttft_miss_p50, 's')} | all p"
                  f"{cfg['slo']['percentile']} {fmt(res.ttft_all_pX, 's')} | "
                  f"decode p50 {fmt(res.decode_p50, ' tok/s', 1)} | "
                  f"{fmt(res.achieved_rps, ' req/s')} | {verdict}")
            if res.blown:
                print("  SLOs clearly blown — stopping the ladder early "
                      "(higher rungs would only stress the endpoint)")
                break


def main(argv=None) -> int:
    args = parse_args(argv)
    cfg = CONFIG
    if args.dry_run:
        return dry_run(args, cfg)

    # one byte-identical prefix for every session in the process — the whole
    # point: vLLM's prefix cache must be able to dedup it across sessions
    state = {
        "rungs": [],
        "current": None,
        "burst": None,
        "system_prefix": make_text(random.Random(0xC0FFEE),
                                   cfg["workload"]["system_prefix_tokens"],
                                   args.chars_per_token),
        # the subagents' own lean prefix — a DIFFERENT byte-stable block,
        # deduplicated among subagents only (used unless sub_shares_prefix)
        "sub_prefix": make_text(random.Random(0x5AB4EF1C),
                                cfg["workload"].get("subagent_prefix_tokens", 3_000),
                                args.chars_per_token),
    }
    interrupted = False
    try:
        asyncio.run(main_async(args, cfg, state))
    except KeyboardInterrupt:
        interrupted = True
    print_report(state, cfg, args, interrupted=interrupted)
    return 130 if interrupted else 0


if __name__ == "__main__":
    sys.exit(main())
