def build_ladder(args, cfg) -> list:
    pred = cfg["predictions"]["predicted_limit_users"]
    mults = [float(x) for x in args.rungs.split(",") if x.strip()]
    pops = {max(1, round(m * pred)) for m in mults}
    # always ladder THROUGH the operating point: ttft_miss_s (and B*) are
    # predictions AT that load, so the verdict needs a rung there
    op = cfg["predictions"].get("operating_point_users")
    if op:
        pops.add(max(1, round(op)))
    return [p for p in sorted(pops) if p <= args.max_users]


def dry_run(args, cfg) -> int:
    """Offline plan + sampler self-check. Exercised in CI-style: exits nonzero
    if the log-normal sampler drifts from its configured median/sigma."""
    wl, slo, pred = cfg["workload"], cfg["slo"], cfg["predictions"]
    ep = cfg["endpoint"]
    print("DRY RUN — plan only, no requests sent\n")
    print(f"endpoint : {args.base_url or ep['base_url']}  "
          f"model={args.model or ep['model']}  "
          f"api key from ${args.api_key_env or ep['api_key_env']}")
    print(f"SLOs     : p{slo['percentile']} TTFT <= {slo['ttft_budget_s']:g}s, "
          f"per-user p50 decode >= {slo['itl_floor_tok_s']:g} tok/s")

    print("\nLOAD LADDER (users; each rung: "
          f"ramp {args.ramp_s:g}s + measure {args.measure_s:g}s)")
    ladder = build_ladder(args, cfg)
    print(f"{'users':>8} {'+sub':>6} {'offered req/s':>14}")
    for pop in ladder:
        n_sub = round(pop * wl["subagent_ratio"])
        print(f"{pop:>8} {n_sub:>6} {(pop + n_sub) / wl['think_time_s']:>14.2f}")
    est = len(ladder) * (args.ramp_s + args.measure_s)
    print(f"full-ladder wall clock (no early stop): ~{est / 60:.0f} min")

    # sampler self-check: the sampled raw median and log-sd must reproduce the
    # configured (median, sigma) — this is the distribution warm capacity and
    # the prefill tail are priced on, so the harness must draw it faithfully
    print("\nPROMPT-LENGTH SAMPLER (n=20,000 per class; tokens, "
          f"clipped to [prefix, {args.context_cap_tokens:,}])")
    rng = random.Random(args.seed)
    failed = False
    hdr = (f"{'class':<10} {'median cfg':>10} {'median smp':>10} "
           f"{'sigma cfg':>9} {'sigma smp':>9} {'p5':>8} {'p50':>8} "
           f"{'p95':>9} {'mean':>9}  check")
    print(hdr)
    # per-class clip floor, mirroring user_loop: subagents clip to THEIR
    # prefix unless sub_shares_prefix — displaying both classes at the user
    # floor overstated the subagent p50 by ~87% under the default config
    sub_floor = (wl["system_prefix_tokens"]
                 if wl.get("sub_shares_prefix", False)
                 else wl.get("subagent_prefix_tokens", 3_000))
    for cls, med, sig, floor in (
            ("user", wl["user_prompt_median_tokens"],
             wl["user_prompt_sigma"], wl["system_prefix_tokens"]),
            ("subagent", wl["subagent_median_tokens"],
             wl["subagent_sigma"], sub_floor)):
        raw = [rng.lognormvariate(math.log(med), sig) for _ in range(20_000)]
        smp_med = pct(raw, 50)
        logs = [math.log(x) for x in raw]
        mu = sum(logs) / len(logs)
        smp_sig = math.sqrt(sum((x - mu) ** 2 for x in logs) / (len(logs) - 1))
        clipped = [min(max(x, floor), args.context_cap_tokens) for x in raw]
        ok = (abs(smp_med / med - 1) < 0.03 and abs(smp_sig / sig - 1) < 0.03)
        failed |= not ok
        print(f"{cls:<10} {med:>10,.0f} {smp_med:>10,.0f} {sig:>9.2f} "
              f"{smp_sig:>9.3f} {pct(clipped, 5):>8,.0f} {pct(clipped, 50):>8,.0f} "
              f"{pct(clipped, 95):>9,.0f} {sum(clipped) / len(clipped):>9,.0f}  "
              f"{'PASS' if ok else 'FAIL'}")
    print(f"(chars per token: {args.chars_per_token:g}; a p50 user prompt is "
          f"~{pct([min(max(x, wl['system_prefix_tokens']), args.context_cap_tokens) for x in [wl['user_prompt_median_tokens']]], 50) * args.chars_per_token / 1e3:,.0f}k chars on the wire)")

    print("\nPREDICTIONS UNDER TEST")
    for k in ("warm_capacity_p5", "decode_ceiling_users", "latency_ceiling_users",
              "saturation_ceiling_users", "binding_constraint",
              "predicted_limit_users", "ttft_miss_s", "bstar_misses",
              "steady_decode_seqs", "steady_decode_tok_s",
              "itl_normal_ms", "itl_worst_freeze_ms"):
        if pred.get(k) is not None:
            print(f"  {k:<26} {pred.get(k)}")
    print("\nHYPOTHESES")
    for h in cfg["hypotheses"]:
        print(f"  - {h}")
    if args.burst:
        burst_pop = args.burst_users or max(1, round(
            pred.get("operating_point_users")
            or 0.5 * pred["predicted_limit_users"]))
        print(f"\n--burst {args.burst}: would run the burst probe instead of "
              f"the ladder (standing load {burst_pop} users)")
    if failed:
        print("\nSAMPLER SELF-CHECK FAILED", file=sys.stderr)
        return 1
    print("\nsampler self-check PASSED; run without --dry-run to measure")
    return 0


