CHECK, CROSS, TILDE = "✓", "✗", "~"


def bracket_verdict(pred: float, lo: float | None, hi: float | None) -> tuple:
    """Compare a predicted ceiling against the measured (largest-pass,
    smallest-fail] population bracket. lo/hi None = side not observed.
    ~ means within 25% of the nearest observed edge."""
    if pred is None:
        return TILDE, "no prediction"
    if lo is None and hi is None:
        return TILDE, "no data"
    if hi is None:                       # never failed: lower bound only
        if pred >= lo:
            return TILDE, f"not reached (measured >= {lo:g}, predicted {pred:g})"
        if lo <= 1.25 * pred:
            return TILDE, f"measured >= {lo:g}, within 25% above prediction"
        return CROSS, f"passed at {lo:g} > 1.25x predicted {pred:g} (model conservative)"
    if lo is None:                       # every rung failed: upper bound only
        if pred <= hi:
            return TILDE, f"capacity < {hi:g}; prediction {pred:g} not excluded"
        if pred <= hi / 0.75:
            return TILDE, f"capacity < {hi:g}, within 25% below prediction"
        return CROSS, f"failed at {hi:g} < 0.75x predicted {pred:g} (model optimistic)"
    if lo <= pred <= hi:
        return CHECK, f"predicted {pred:g} inside measured ({lo:g}, {hi:g}]"
    edge = lo if pred < lo else hi
    if 0.75 <= pred / edge <= 1.25:
        return TILDE, f"predicted {pred:g} within 25% of measured ({lo:g}, {hi:g}]"
    return CROSS, f"predicted {pred:g} outside measured ({lo:g}, {hi:g}]"


def print_report(state: dict, cfg, args, interrupted: bool = False):
    slo, pred = cfg["slo"], cfg["predictions"]
    p = slo["percentile"]
    rungs: list[RungResult] = list(state["rungs"])
    # a partially-measured current rung still carries information on Ctrl-C
    if interrupted and state.get("current"):
        pop, n_sub, turns, ms = state["current"]
        if ms is not None and any(t.t_start >= ms for t in turns):
            r = eval_rung(pop, n_sub, turns, ms, cfg, args)
            r.partial = True           # shown for orientation, excluded from verdicts
            rungs.append(r)

    print("\n" + "=" * 78)
    print("VALIDATION REPORT" + ("  [INTERRUPTED — partial]" if interrupted else ""))
    print("=" * 78)

    if rungs:
        print(f"\n{'users':>6} {'turns':>6} {'hit':>5} {'miss':>5} {'err':>4} "
              f"{'TTFT hit p50/p' + str(p):>17} {'TTFT miss p50/p' + str(p):>18} "
              f"{'dec p50':>8} {'req/s':>6} {'verdict'}")
        for r in rungs:
            verdict = "PASS" if r.passed else "FAIL: " + "; ".join(r.reasons)
            if r.partial:
                verdict += " [partial — not counted]"
            print(f"{r.pop:>6} {r.n_turns:>6} {r.n_hit:>5} {r.n_miss:>5} "
                  f"{r.n_err:>4} "
                  f"{fmt(r.ttft_hit_p50, '', 2):>8}/{fmt(r.ttft_hit_pX, 's', 2):<8} "
                  f"{fmt(r.ttft_miss_p50, '', 2):>8}/{fmt(r.ttft_miss_pX, 's', 2):<9} "
                  f"{fmt(r.decode_p50, '', 1):>8} {fmt(r.achieved_rps, '', 2):>6} "
                  f"{verdict}")
        # ---- ITL gap table: what the chunk size actually moves -------------
        if any(math.isfinite(r.itl_p50_ms) for r in rungs):
            thr = args.freeze_threshold_ms
            print(f"\nINTER-TOKEN GAPS (freeze = a gap >= {thr:g} ms)")
            print(f"{'users':>6} {'normal p50':>11} {'worst/resp p50':>15} "
                  f"{'worst/resp p95':>15} {'worst seen':>11} "
                  f"{'freezes/ktok':>13} {'time stalled':>13}")
            for r in rungs:
                print(f"{r.pop:>6} {fmt(r.itl_p50_ms, ' ms', 1):>11} "
                      f"{fmt(r.itl_worst_p50_ms, ' ms', 0):>15} "
                      f"{fmt(r.itl_worst_p95_ms, ' ms', 0):>15} "
                      f"{fmt(r.itl_max_ms, ' ms', 0):>11} "
                      f"{fmt(r.freeze_per_ktok, '', 1):>13} "
                      f"{fmt(r.stall_frac * 100 if math.isfinite(r.stall_frac) else float('nan'), '%', 1):>13}")
            cr = [r.chunk_tok_ratio for r in rungs
                  if math.isfinite(r.chunk_tok_ratio)]
            if cr and abs(pct(cr, 50) - 1.0) > 0.05:
                print(f"  NOTE: {pct(cr, 50):.2f} tokens per SSE event — gaps are "
                      "per event, so per-token gaps are finer than shown.")

        ratios = [r.ptok_ratio for r in rungs if math.isfinite(r.ptok_ratio)]
        if ratios:
            med = pct(ratios, 50)
            print(f"\nachieved/intended prompt tokens (median): {med:.2f} "
                  f"(tokens ~ chars/{args.chars_per_token:g}; if far from 1.0, "
                  f"re-run with --chars-per-token {args.chars_per_token / med:.1f})")

    # measured SLO capacity bracket — full windows only; a partial rung is
    # orientation, not evidence
    rungs = [r for r in rungs if not r.partial]
    passes = [r.pop for r in rungs if r.passed]
    fails = [r.pop for r in rungs if not r.passed]
    lo = max(passes) if passes else None
    hi = min(fails) if fails else None
    print("\nMEASURED SLO CAPACITY "
          f"(p{p} TTFT <= {slo['ttft_budget_s']:g}s AND per-user p50 decode "
          f">= {slo['itl_floor_tok_s']:g} tok/s):")
    if lo is not None and hi is not None:
        print(f"  in ({lo}, {hi}] — largest passing population {lo} users")
    elif lo is not None:
        print(f"  >= {lo} users (no failing rung observed — a lower bound)")
    elif hi is not None:
        print(f"  < {hi} users (no passing rung observed)")
    else:
        print("  not measured")

    # failure-mode split: which ceilings did the ladder actually see?
    ttft_fails = [r.pop for r in rungs
                  if any("TTFT" in s for s in r.reasons)]
    dec_fails = [r.pop for r in rungs
                 if any("decode" in s for s in r.reasons)]
    lat_lo = max((r.pop for r in rungs
                  if r.passed or not any("TTFT" in s for s in r.reasons)),
                 default=None)
    dec_lo = max((r.pop for r in rungs
                  if r.passed or not any("decode" in s for s in r.reasons)),
                 default=None)

    print("\nPREDICTED vs MEASURED")
    print(f"{'quantity':<28} {'predicted':>10} {'measured':>22}  verdict")

    def row(name, predicted, measured, verdict, note):
        print(f"{name:<28} {predicted:>10} {measured:>22}  {verdict}  {note}")

    # binding limit
    v, note = bracket_verdict(pred.get("predicted_limit_users"), lo, hi)
    row(f"SLO capacity ({pred.get('binding_constraint', '?')} binds)",
        f"{pred.get('predicted_limit_users', '-')}",
        (f"({lo},{hi}]" if lo is not None and hi is not None
         else f">={lo}" if lo is not None else f"<{hi}" if hi is not None else "-"),
        v, note)

    # latency ceiling: separable only if a rung failed on TTFT
    if ttft_fails:
        v, note = bracket_verdict(pred.get("latency_ceiling_users"),
                                  lat_lo, min(ttft_fails))
        row("latency ceiling", f"{pred.get('latency_ceiling_users', '-')}",
            f"({lat_lo},{min(ttft_fails)}]", v, note)
    else:
        row("latency ceiling", f"{pred.get('latency_ceiling_users', '-')}",
            "not separable", TILDE, "no TTFT-mode failure observed")

    # decode ceiling: separable only if a rung failed on the floor
    if dec_fails:
        v, note = bracket_verdict(pred.get("decode_ceiling_users"),
                                  dec_lo, min(dec_fails))
        row("decode ceiling", f"{pred.get('decode_ceiling_users', '-')}",
            f"({dec_lo},{min(dec_fails)}]", v, note)
    else:
        row("decode ceiling", f"{pred.get('decode_ceiling_users', '-')}",
            "not separable", TILDE, "no decode-floor failure observed")

    # saturation: visible as achieved req/s falling well under the offered rate
    sat_evidence = [r for r in rungs if not r.passed and r.n_turns > 0
                    and math.isfinite(r.achieved_rps)
                    and r.achieved_rps < 0.7 * r.offered_rps]
    if sat_evidence:
        r0 = min(sat_evidence, key=lambda r: r.pop)
        row("saturation ceiling", f"{pred.get('saturation_ceiling_users', '-')}",
            f"<= {r0.pop}", TILDE,
            f"achieved {r0.achieved_rps:.2f} req/s vs offered "
            f"{r0.offered_rps:.2f} — throughput plateau")
    else:
        row("saturation ceiling", f"{pred.get('saturation_ceiling_users', '-')}",
            "not separable", TILDE,
            "closed loop throttles before duty=100% is visible")

    # warm capacity: bounded below by the largest population whose hit turns
    # stayed warm (low effective-cold fraction), never bounded above here
    held = [r.pop for r in rungs if r.n_hit > 0
            and (not math.isfinite(r.evict_frac) or r.evict_frac < 0.05)]
    wc = pred.get("warm_capacity_p5")
    if held:
        bound = max(held)
        if wc is not None and bound >= wc:
            row("warm capacity (p5)", f"{wc}", f">= {bound}", CHECK,
                "held at/above prediction with <5% effective-cold hits (lower bound)")
        else:
            row("warm capacity (p5)", f"{wc}", f">= {bound}", TILDE,
                "lower bound only — eviction not reached")
    else:
        evicted = [r for r in rungs if math.isfinite(r.evict_frac)
                   and r.evict_frac >= 0.05]
        if evicted:
            r0 = min(evicted, key=lambda r: r.pop)
            v = (CROSS if wc is not None and r0.pop < 0.75 * wc else TILDE)
            row("warm capacity (p5)", f"{wc}", f"< ~{r0.pop}", v,
                f"{r0.evict_frac:.0%} of hit turns re-prefilled at {r0.pop} users")
        else:
            row("warm capacity (p5)", f"{wc}", "not separable", TILDE, "no data")

    # miss TTFT level — read at the rung nearest the OPERATING POINT the
    # prediction was computed at (the explorer's Concurrent-users setting):
    # ttft_miss rises steeply with load, so sampling it at the predicted
    # LIMIT instead systematically failed a correct model
    tm = pred.get("ttft_miss_s")
    cand = [r for r in rungs if r.n_miss > 0 and math.isfinite(r.ttft_miss_mean)]
    if cand and tm:
        tgt = (pred.get("operating_point_users")
               or pred.get("predicted_limit_users") or cand[-1].pop)
        r0 = min(cand, key=lambda r: abs(r.pop - tgt))
        ratio = r0.ttft_miss_mean / tm
        v = CHECK if 0.7 <= ratio <= 1.3 else (TILDE if 0.5 <= ratio <= 2.0 else CROSS)
        row("miss mean TTFT", f"{tm:g}s", f"{r0.ttft_miss_mean:.2f}s @ {r0.pop}u",
            v, f"{ratio:.2f}x predicted at the ~{tgt}-user operating point "
               f"(model quotes order-of-magnitude bounds)")
    else:
        row("miss mean TTFT", f"{tm if tm else '-'}", "not separable", TILDE,
            "no forced-miss samples")

    # B* (burst mode only)
    bstar = pred.get("bstar_misses")
    b = state.get("burst")
    if b and b.get("last_ttft_s") is not None:
        within = b["n"] <= (bstar or 0)
        met = b["last_ttft_s"] <= slo["ttft_budget_s"]
        v = CHECK if within == met else (
            TILDE if bstar and 0.75 <= b["n"] / bstar <= 1.33 else CROSS)
        row("B* (burst tolerance)", f"{bstar}",
            f"N={b['n']}: last {b['last_ttft_s']:.2f}s", v,
            ("burst <= B* drained inside budget" if within and met else
             "burst > B* breached budget, as predicted" if not within and not met else
             "outcome contradicts B*"))
    else:
        row("B* (burst tolerance)", f"{bstar}", "not measured", TILDE,
            "run with --burst N to probe the correlated-flush tolerance")

    # ------------------------------------------------------------------
    print("\nWHAT THIS RUN DOES NOT ESTABLISH")
    notes = [
        "Warm capacity is bounded BELOW only: unless a rung shows >5% "
        "effective-cold hit turns, the pool was never driven to eviction, and "
        "the eviction classifier itself is the baseline's 0.4x-cold TTFT "
        "heuristic, not a pool measurement.",
        "Ceilings the ladder did not fail on are 'not separable': one run "
        "observes one binding constraint, not four.",
        "Token counts are chars/{:g} approximations; the achieved/intended "
        "ratio above says how far off — re-run calibrated before trusting "
        "capacity numbers to better than ~15%.".format(args.chars_per_token),
        "Think time is exponential around a fixed mean; real agentic cadence "
        "is burstier (lognormal sigma 2.43 in the measured trace), which "
        "moves the latency ceiling down, not up.",
        "One seed, one window per rung: no variance estimate. Steady state is "
        "assumed after the ramp, not verified.",
        "DP deployments: this drives ONE endpoint; replica-splitting and "
        "session-sticky routing are not exercised.",
    ]
    wl_n = cfg["workload"]
    sub_floor = (wl_n["system_prefix_tokens"]
                 if wl_n.get("sub_shares_prefix", False)
                 else wl_n.get("subagent_prefix_tokens", 3_000))
    if sub_floor >= wl_n["subagent_median_tokens"]:
        notes.append(
            "Subagent leg is DEGENERATE under this config: the prefix floor "
            f"({sub_floor:,} tok) >= the subagent median "
            f"({wl_n['subagent_median_tokens']:,} tok), so most subagent "
            "first turns are byte-identical and vLLM dedups them to one "
            "cache entry — the subagent KV load is not being exercised.")
    if not state.get("burst"):
        notes.append("Correlated-flush tolerance (B*) needs the separate "
                     "--burst mode; the ladder's independent per-turn misses "
                     "cannot see it.")
    for s in notes:
        print(f"  - {s}")

    if args.json:
        out = {
            "config": cfg,
            "rungs": [vars(r) for r in rungs],
            "burst": state.get("burst"),
            "measured_capacity_bracket": [lo, hi],
            "interrupted": interrupted,
        }
        with open(args.json, "w") as f:
            json.dump(out, f, indent=2, default=str)
        print(f"\nraw results written to {args.json}")


