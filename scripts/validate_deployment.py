"""
Live-endpoint validation harness for the serving-capacity model
(scripts/scenario_model.py; interactive/index.html mirrors it in JS).

The model predicts four ceilings for a configuration — cache (warm p5),
decode (users at the tok/s floor), latency (users where a miss's mean TTFT
hits the budget) and saturation (prefill duty 100%) — and the binding one
is the smallest. Every one of those is a projection: docs/scenarios.md
("Planning stance") is explicit that the study is a hypothesis generator
and that "comfortable capacity" is DEFINED as measured SLO capacity, a
number the model cannot produce. This script is that measurement: it
drives a LIVE vLLM endpoint with the closed-loop workload the model
assumes and finds the real limit.

  MEASURED SLO CAPACITY := the largest simulated population meeting
      p{percentile} TTFT <= ttft_budget_s
      AND per-user p50 decode >= itl_floor_tok_s
  over a geometric load ladder bracketing the model's predicted limit.

Workload (one simulated user = one session, assumption 1 of the planner):
every session shares ONE byte-identical system prefix (so vLLM prefix
caching engages), carries a per-session context drawn from the model's
log-normal (median/sigma; tokens ~ chars/4, and the ACHIEVED prompt_tokens
are read back from `usage` and reported against the intent), and loops:
think (exponential, mean think_time_s) -> send prior context + a
warm_turn_tokens turn -> stream the response. With probability miss_rate a
turn prepends a random salt, making the whole request unmatchable — the
model's cache miss. Subagent sessions (ratio r, leaner prompts) run the
same loop with their OWN byte-stable prefix (subagent_prefix_tokens),
exactly as Workload prices them — unless sub_shares_prefix points both
classes at the single user prefix.

What one run establishes, and what it cannot: the ladder separates the
ceilings only by their observed failure mode (TTFT breach vs decode-floor
breach); warm capacity is bounded BELOW unless the run reaches eviction;
correlated-flush tolerance (B*) needs --burst. The verdict table names
which is which — read the "what this run does not establish" trailer
before quoting any number from it.

Usage:
    uv run validate_deployment.py --dry-run        # offline: plan + sampler self-check
    uv run validate_deployment.py --base-url http://host:8000/v1
    uv run validate_deployment.py --burst 8        # B* probe instead of the ladder

Ctrl-C at any point prints a partial report over the rungs completed.
"""
