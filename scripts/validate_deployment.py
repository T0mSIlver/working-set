# measurement records
# ============================================================================
@dataclass
class Turn:
    uid: int
    is_sub: bool
    kind: str                 # "first" (session establishment) | "hit" | "miss"
    t_start: float
    ttft: float | None = None
    decode_tps: float | None = None
    ptok_intended: int = 0
    ptok_achieved: int | None = None
    ctok: int | None = None
    error: str | None = None
    # --- inter-token gap stats (the ITL-spike evidence) ---------------------
    # decode_tps above is a MEAN over the whole stream and is nearly blind to a
    # freeze: a single 1.3 s stall inside a 1,000-token response otherwise
    # running at 200 tok/s reads as ~159 tok/s — a 20% dip standing in for a
    # 260x spike. These fields keep the distribution the mean throws away.
    # Gaps are measured per SSE EVENT, not per token; chunk_tok_ratio in the
    # report says how far apart those two are on this endpoint.
    itl_p50: float | None = None      # s, median gap within this response
    itl_max: float | None = None      # s, worst gap within this response
    n_gaps: int = 0
    n_freeze: int = 0                 # gaps >= the freeze threshold
    stall_s: float = 0.0              # total time inside those gaps
    span_s: float | None = None       # t_last - t_first
    n_chunks: int = 0


@dataclass
class RungResult:
    pop: int                  # user-class sessions (the population axis)
    n_sub: int
    n_turns: int = 0
    n_hit: int = 0
    n_miss: int = 0
    n_err: int = 0
    ttft_hit_p50: float = float("nan")
    ttft_hit_pX: float = float("nan")
    ttft_miss_p50: float = float("nan")
    ttft_miss_pX: float = float("nan")
    ttft_miss_mean: float = float("nan")
    ttft_all_pX: float = float("nan")
    decode_p50: float = float("nan")
    # --- ITL gap distribution (see Turn) ---
    itl_p50_ms: float = float("nan")        # the normal inter-token gap
    itl_worst_p50_ms: float = float("nan")  # typical worst freeze, per response
    itl_worst_p95_ms: float = float("nan")  # unlucky response's worst freeze
    itl_max_ms: float = float("nan")        # worst freeze seen anywhere
    freeze_per_ktok: float = float("nan")   # gaps >= threshold per 1k tokens
    stall_frac: float = float("nan")        # share of decode time inside them
    chunk_tok_ratio: float = float("nan")   # tokens per SSE event (1.0 = per-token)
    achieved_rps: float = float("nan")
    offered_rps: float = float("nan")
    evict_frac: float = float("nan")   # hit-intended turns that look cold (heuristic)
    ptok_ratio: float = float("nan")   # achieved / intended prompt tokens, median
    passed: bool = False
    reasons: list = field(default_factory=list)
    blown: bool = False                # SLOs clearly blown -> ladder stops here
    partial: bool = False              # interrupted mid-window: shown, never counted


# ============================================================================
# one streamed request against the OpenAI-compatible /v1/completions
# ============================================================================
async def send_turn(client, args, cfg, prompt: str, turn: Turn) -> str:
    """Stream one completion; fills `turn` in place, returns the response text
    (appended to the session so the next warm turn extends the cached run)."""
    ep = cfg["endpoint"]
    payload = {
        "model": args.model or ep["model"],
        "prompt": prompt,
        "max_tokens": cfg["workload"]["max_output_tokens"],
        "temperature": 0.7,
        "stream": True,
        "stream_options": {"include_usage": True},
    }
    if not args.no_ignore_eos:
        # vLLM extension: guarantees max_output_tokens of decode per turn, so
        # decode tok/s is measured over a fixed-length stream, not over
        # whatever an early EOS leaves. Strict non-vLLM endpoints: disable.
        payload["ignore_eos"] = True
    headers = {}
    key = os.environ.get(args.api_key_env or ep["api_key_env"] or "", "")
    if key:
        headers["Authorization"] = f"Bearer {key}"

    base = (args.base_url or ep["base_url"]).rstrip("/")
    t0 = time.monotonic()
    t_first = t_last = None
    n_chunks, text, usage = 0, [], None
    gaps: list[float] = []
    try:
        async with client.stream("POST", f"{base}/completions", json=payload,
                                 headers=headers,
                                 timeout=args.request_timeout_s) as r:
            r.raise_for_status()
            async for line in r.aiter_lines():
                if not line.startswith("data:"):
                    continue
                data = line[5:].strip()
                if data == "[DONE]":
                    break
                obj = json.loads(data)
                if obj.get("usage"):
                    usage = obj["usage"]
                ch = obj.get("choices") or []
                if ch and ch[0].get("text"):
                    now = time.monotonic()
                    if t_first is None:
                        t_first = now
                        turn.ttft = now - t0
                    else:
                        gaps.append(now - t_last)
                    t_last = now
                    n_chunks += 1
                    text.append(ch[0]["text"])
    except asyncio.CancelledError:
        raise
    except Exception as e:  # connection, HTTP status, timeout, bad JSON
        turn.error = f"{type(e).__name__}: {e}"[:200]
        return ""

    if usage:
        turn.ptok_achieved = usage.get("prompt_tokens")
        turn.ctok = usage.get("completion_tokens")
    n_tok = turn.ctok if turn.ctok else n_chunks
    if t_first is not None and t_last is not None and t_last > t_first and n_tok > 1:
        turn.decode_tps = (n_tok - 1) / (t_last - t_first)
        turn.span_s = t_last - t_first
    turn.n_chunks = n_chunks
    if gaps:
        freeze_s = args.freeze_threshold_ms / 1e3
        big = [g for g in gaps if g >= freeze_s]
        turn.itl_p50 = pct(gaps, 50)
        turn.itl_max = max(gaps)
        turn.n_gaps = len(gaps)
        turn.n_freeze = len(big)
        turn.stall_s = sum(big)
    return "".join(text)


# ============================================================================
# closed-loop session
# ============================================================================
async def user_loop(client, args, cfg, uid: int, is_sub: bool,
                    system_prefix: str, sub_prefix: str, turns: list,
                    stop: asyncio.Event, stagger_s: float):
    wl = cfg["workload"]
    rng = random.Random((args.seed << 20) ^ uid)
    cpt = args.chars_per_token
    median = wl["subagent_median_tokens"] if is_sub else wl["user_prompt_median_tokens"]
    sigma = wl["subagent_sigma"] if is_sub else wl["user_prompt_sigma"]
    # each request class carries ITS OWN byte-stable prefix, exactly as
    # Workload.sample prices it: subagents get the lean sub prefix unless
    # sub_shares_prefix points them at the user prefix (the old behaviour
    # — always the user prefix — silently tested a ~3x lighter subagent
    # workload than the one the predictions were computed on)
    own_sub = is_sub and not wl.get("sub_shares_prefix", False)
    prefix_tok = wl.get("subagent_prefix_tokens", 3_000) if own_sub \
        else wl["system_prefix_tokens"]
    prefix_txt = sub_prefix if own_sub else system_prefix
    full = draw_session_tokens(rng, median, sigma, prefix_tok,
                               args.context_cap_tokens)
    # per-session unique context on top of this class's shared prefix
    ctx = make_text(rng, max(full - prefix_tok, 0), cpt)
    history = ""
    n_turn = 0
    cap = args.turns_per_user or math.inf

    await asyncio.sleep(stagger_s)          # spread session establishment over the ramp
    while not stop.is_set() and n_turn < cap:
        first = n_turn == 0
        if not first:
            # exponential think time; wake early if the rung ends
            try:
                await asyncio.wait_for(stop.wait(),
                                       rng.expovariate(1.0 / wl["think_time_s"]))
                break
            except asyncio.TimeoutError:
                pass
        is_miss = (not first) and rng.random() < wl["miss_rate"]
        # a salt ahead of the prefix makes the WHOLE request unmatchable — the
        # model's cache miss (full re-prefill), applied to this turn only
        salt = f"[miss-salt {rng.getrandbits(64):016x}] " if is_miss else ""
        turn_text = "" if first else "\n" + make_text(rng, wl["warm_turn_tokens"], cpt)
        prompt = salt + prefix_txt + "\n" + ctx + history + turn_text
        turn = Turn(uid=uid, is_sub=is_sub,
                    kind="first" if first else ("miss" if is_miss else "hit"),
                    t_start=time.monotonic(),
                    ptok_intended=int(len(prompt) / cpt))
        turns.append(turn)
        reply = await send_turn(client, args, cfg, prompt, turn)
        # the response joins the context: the next warm turn extends the cached
        # sequence exactly the way a real agentic session does
        history += turn_text + reply
        n_turn += 1


# ============================================================================
# one ladder rung
# ============================================================================
def eval_rung(pop: int, n_sub: int, turns: list, measure_start: float,
              cfg, args) -> RungResult:
    slo, wl = cfg["slo"], cfg["workload"]
    p = slo["percentile"]
    res = RungResult(pop=pop, n_sub=n_sub)

    measured = [t for t in turns
                if t.t_start >= measure_start and t.kind in ("hit", "miss")]
    res.n_err = sum(1 for t in measured if t.error)
    ok = [t for t in measured if not t.error and t.ttft is not None]
    hit = [t for t in ok if t.kind == "hit"]
    miss = [t for t in ok if t.kind == "miss"]
    res.n_turns, res.n_hit, res.n_miss = len(ok), len(hit), len(miss)

    res.ttft_hit_p50 = pct([t.ttft for t in hit], 50)
    res.ttft_hit_pX = pct([t.ttft for t in hit], p)
    res.ttft_miss_p50 = pct([t.ttft for t in miss], 50)
    res.ttft_miss_pX = pct([t.ttft for t in miss], p)
    if miss:
        res.ttft_miss_mean = sum(t.ttft for t in miss) / len(miss)
    res.ttft_all_pX = pct([t.ttft for t in ok], p)

    # per-user decode: median within each user, then p50 across users — the
    # model's "per-user p50" is a population statistic, not a turn statistic
    by_user: dict[int, list] = {}
    for t in ok:
        if t.decode_tps is not None:
            by_user.setdefault(t.uid, []).append(t.decode_tps)
    res.decode_p50 = pct([pct(v, 50) for v in by_user.values()], 50)

    # ITL gap distribution. decode_p50 above answers "how fast on average";
    # these answer "what did it feel like" — the chunk-size hypothesis lives
    # entirely here, because chunking moves the tail and leaves the mean flat.
    g = [t for t in ok if t.n_gaps > 0]
    if g:
        res.itl_p50_ms = pct([t.itl_p50 for t in g], 50) * 1e3
        worst = [t.itl_max for t in g]
        res.itl_worst_p50_ms = pct(worst, 50) * 1e3
        res.itl_worst_p95_ms = pct(worst, 95) * 1e3
        res.itl_max_ms = max(worst) * 1e3
        n_gaps = sum(t.n_gaps for t in g)
        if n_gaps:
            res.freeze_per_ktok = 1e3 * sum(t.n_freeze for t in g) / n_gaps
        span = sum(t.span_s for t in g if t.span_s)
        if span > 0:
            res.stall_frac = sum(t.stall_s for t in g) / span
        chunks = sum(t.n_chunks for t in g)
        ctoks = sum(t.ctok for t in g if t.ctok)
        if chunks and ctoks:
            res.chunk_tok_ratio = ctoks / chunks

    res.achieved_rps = len(measured) / args.measure_s
    res.offered_rps = (pop + n_sub) / wl["think_time_s"]

    # eviction heuristic (the baseline's warm/cold classifier): a hit-intended
    # turn whose TTFT is >= 0.4x the median forced-miss TTFT re-prefilled — its
    # cached run was evicted. A heuristic, flagged as such in the report.
    if hit and miss and math.isfinite(res.ttft_miss_p50):
        thresh = 0.4 * res.ttft_miss_p50
        res.evict_frac = sum(1 for t in hit if t.ttft >= thresh) / len(hit)

    ratios = [t.ptok_achieved / t.ptok_intended for t in ok
              if t.ptok_achieved and t.ptok_intended]
    res.ptok_ratio = pct(ratios, 50)

    # SLO verdict for this rung
    budget, floor = slo["ttft_budget_s"], slo["itl_floor_tok_s"]
    err_frac = res.n_err / max(len(measured), 1)
    if not ok:
        res.reasons.append("no successful turns in the measure window")
        res.blown = True
    else:
        if err_frac > 0.05:
            res.reasons.append(f"error rate {err_frac:.0%}")
        if res.ttft_all_pX > budget:
            res.reasons.append(f"p{p} TTFT {res.ttft_all_pX:.2f}s > {budget:g}s")
        if math.isfinite(res.decode_p50) and res.decode_p50 < floor:
            res.reasons.append(f"decode p50 {res.decode_p50:.1f} < {floor:g} tok/s")
        res.blown = (res.ttft_all_pX > 2 * budget
                     or (math.isfinite(res.decode_p50)
                         and res.decode_p50 < 0.5 * floor)
                     or err_frac > 0.20)
    res.passed = not res.reasons
    return res


async def run_rung(client, args, cfg, pop: int, state: dict) -> RungResult:
    wl = cfg["workload"]
    n_sub = round(pop * wl["subagent_ratio"])
    turns: list[Turn] = []
    state["current"] = (pop, n_sub, turns, None)
    stop = asyncio.Event()
    system_prefix = state["system_prefix"]

    tasks = []
    rng = random.Random(args.seed ^ pop)
    for i in range(pop + n_sub):
        tasks.append(asyncio.create_task(user_loop(
            client, args, cfg, uid=pop * 100_000 + i, is_sub=(i >= pop),
            system_prefix=system_prefix, sub_prefix=state["sub_prefix"],
            turns=turns, stop=stop,
            stagger_s=rng.uniform(0, max(args.ramp_s, 1.0)))))
    t0 = time.monotonic()
    measure_start = t0 + args.ramp_s
    state["current"] = (pop, n_sub, turns, measure_start)
    try:
        await asyncio.sleep(args.ramp_s + args.measure_s)
    finally:
        stop.set()
        for t in tasks:
            t.cancel()
        await asyncio.gather(*tasks, return_exceptions=True)

    res = eval_rung(pop, n_sub, turns, measure_start, cfg, args)
    state["rungs"].append(res)
    state["current"] = None
    return res


# ============================================================================
# burst probe  (--burst N: validates B*, the correlated-flush tolerance)
# ============================================================================
async def run_burst(client, args, cfg, state: dict):
    """From steady standing load, fire N simultaneous forced misses and time
    the drain. B* predicts the largest N whose LAST first-token still lands
    inside the TTFT budget (spike_tolerance in scenario_model.py)."""
    wl = cfg["workload"]
    pred = cfg["predictions"]
    # standing load defaults to the OPERATING POINT the B* prediction was
    # computed at (old default 0.5 x limit drained the burst into a
    # different duty cycle than the one that priced it)
    pop = args.burst_users or max(1, round(
        pred.get("operating_point_users")
        or 0.5 * pred["predicted_limit_users"]))
    n_sub = round(pop * wl["subagent_ratio"])
    n = args.burst
    print(f"\nBURST PROBE: standing load {pop} users (+{n_sub} subagents), "
          f"ramp {args.ramp_s:g}s, then {n} simultaneous forced misses "
          f"(predicted B* = {pred['bstar_misses']:g})")

    turns: list[Turn] = []
    stop = asyncio.Event()
    rng = random.Random(args.seed ^ 0xB0057)
    tasks = [asyncio.create_task(user_loop(
        client, args, cfg, uid=900_000 + i, is_sub=(i >= pop),
        system_prefix=state["system_prefix"], sub_prefix=state["sub_prefix"],
        turns=turns, stop=stop,
        stagger_s=rng.uniform(0, max(args.ramp_s, 1.0))))
        for i in range(pop + n_sub)]
    try:
        await asyncio.sleep(args.ramp_s)

        async def one_miss(i: int) -> Turn:
            r = random.Random((args.seed << 8) ^ (0xF00D + i))
            full = draw_session_tokens(r, wl["user_prompt_median_tokens"],
                                       wl["user_prompt_sigma"],
                                       wl["system_prefix_tokens"],
                                       args.context_cap_tokens)
            salt = f"[miss-salt {r.getrandbits(64):016x}] "
            prompt = (salt + state["system_prefix"] + "\n"
                      + make_text(r, max(full - wl["system_prefix_tokens"], 0),
                                  args.chars_per_token))
            t = Turn(uid=990_000 + i, is_sub=False, kind="miss",
                     t_start=time.monotonic(),
                     ptok_intended=int(len(prompt) / args.chars_per_token))
            await send_turn(client, args, cfg, prompt, t)
            return t

        t_fire = time.monotonic()
        burst_turns = await asyncio.gather(*[one_miss(i) for i in range(n)])
    finally:
        stop.set()
        for t in tasks:
            t.cancel()
        await asyncio.gather(*tasks, return_exceptions=True)

    ok = [t for t in burst_turns if t.ttft is not None and not t.error]
    result = {
        "n": n, "standing_users": pop,
        "n_ok": len(ok), "n_err": n - len(ok),
        # drain: fire -> the LAST request's first token (all fired together,
        # so last first-token = the fluid model's T_drain, whatever the
        # scheduler's discipline — see burst_drain_seconds)
        "drain_s": (max(t.t_start + t.ttft for t in ok) - t_fire) if ok else None,
        "last_ttft_s": max((t.ttft for t in ok), default=None),
        "ttft_p50_s": pct([t.ttft for t in ok], 50),
    }

    # What the STANDING load felt while the burst was draining. This is the
    # chunk-size hypothesis in its purest form: the burst is a controlled
    # cold-prefill event, and these are the decoders it lands on. Only turns
    # still streaming at fire time can have been hit by it.
    victims = [t for t in turns
               if t.n_gaps > 0 and t.span_s
               and t.t_start <= t_fire <= t.t_start + (t.ttft or 0) + t.span_s]
    if victims:
        worst = [t.itl_max for t in victims]
        result["standing_n"] = len(victims)
        result["standing_itl_p50_ms"] = pct([t.itl_p50 for t in victims], 50) * 1e3
        result["standing_worst_p50_ms"] = pct(worst, 50) * 1e3
        result["standing_worst_max_ms"] = max(worst) * 1e3
        n_gaps = sum(t.n_gaps for t in victims)
        result["standing_freeze_per_ktok"] = (
            1e3 * sum(t.n_freeze for t in victims) / n_gaps) if n_gaps else None

    state["burst"] = result
    print(f"  burst: {len(ok)}/{n} answered | TTFT p50 {fmt(result['ttft_p50_s'], 's')} "
          f"| last first-token {fmt(result['last_ttft_s'], 's')} "
          f"| drain {fmt(result['drain_s'], 's')}")
    if victims:
        print(f"  standing load hit by it: {len(victims)} responses in flight | "
              f"normal gap {fmt(result['standing_itl_p50_ms'], ' ms', 1)} | "
              f"worst gap p50 {fmt(result['standing_worst_p50_ms'], ' ms', 0)} | "
              f"worst seen {fmt(result['standing_worst_max_ms'], ' ms', 0)}")


